/**
 * Zero-dependency bundler for content script modules.
 * Combines shared/constants.js, shared/messaging.js, content/activity-tracker.js,
 * content/lock-screen.js, and content/content-main.js into content/content-bundle.js
 * so Chrome MV3 can load the content script synchronously without web_accessible_resources.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const filesToBundle = [
  'shared/constants.js',
  'shared/messaging.js',
  'content/activity-tracker.js',
  'content/lock-screen.js',
  'content/content-main.js'
];

function stripModuleSyntax(source) {
  // Remove multi-line and single-line import statements
  let cleaned = source.replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '');
  // Remove leading 'export ' from declarations (export const, export function, export async function, export class)
  cleaned = cleaned.replace(/^export\s+(?=(const|let|var|function|async\s+function|class)\b)/gm, '');
  return cleaned.trim();
}

const chunks = filesToBundle.map(relPath => {
  const fullPath = path.join(rootDir, relPath);
  const raw = fs.readFileSync(fullPath, 'utf8');
  return `// === Module: ${relPath} ===\n${stripModuleSyntax(raw)}`;
});

const bundleOutput = `/**
 * Instagram Lock - Content Script Bundle (Auto-generated by scripts/build-content.mjs)
 * Runs directly in Chrome's Isolated World with zero web_accessible_resources exposure.
 */
(() => {
  'use strict';

${chunks.join('\n\n')}

  // Auto-initialize content script
  Promise.resolve()
    .then(() => init())
    .catch((err) => {
      console.error('[IG-Lock Security] Bundle initialization failed:', err);
      if (typeof globalThis.__igLockFailClosed === 'function') {
        globalThis.__igLockFailClosed();
      }
    });
})();
`;

const outPath = path.join(rootDir, 'content', 'content-bundle.js');
fs.writeFileSync(outPath, bundleOutput, 'utf8');
console.log(`Built ${outPath} (${bundleOutput.length} bytes)`);
